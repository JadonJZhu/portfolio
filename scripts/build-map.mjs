// Turns data/ into src/map-data.js (the fly-through) and assets/map/*.svg (plain page thumbnails).
// data/route.json: `points` is the route from spawn in map units (0 to 100); `stops` are the screens
// in order (`point` indexes it; `room` is checked here, never shipped). `corridor` is the straight
// north to south run of the ten timeline entries; `years` are Jan marks placed along it by date.
// `labels` are the only text on the map; `callouts` are the buy-phase and map-overlay buttons.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const map = JSON.parse(readFileSync('data/tannery-row.json', 'utf8'));
const route = JSON.parse(readFileSync('data/route.json', 'utf8'));
const SIZE = 100;

// Traces the outline of a set of grid cells as closed loops: an SVG path, plus straight segments.
const walls = [];
function outline(isIn, keepWalls = false) {
  const next = new Map();
  const edge = (a, b) => next.set(a.join(), b);
  for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
    if (!isIn(x, y)) continue;
    if (!isIn(x, y - 1)) edge([x, y], [x + 1, y]);
    if (!isIn(x + 1, y)) edge([x + 1, y], [x + 1, y + 1]);
    if (!isIn(x, y + 1)) edge([x + 1, y + 1], [x, y + 1]);
    if (!isIn(x - 1, y)) edge([x, y + 1], [x, y]);
  }
  let d = '';
  while (next.size) {
    const start = next.keys().next().value;
    let key = start, last = null, loop = [];
    do {
      const to = next.get(key);
      next.delete(key);
      const from = key.split(',').map(Number);
      const dir = [to[0] - from[0], to[1] - from[1]].join();
      if (dir !== last) loop.push(from);
      last = dir;
      key = to.join();
    } while (key !== start && next.has(key));
    d += 'M' + loop.map((p) => p.join(' ')).join('L') + 'Z';
    if (keepWalls) loop.forEach((p, i) => walls.push([...p, ...loop[(i + 1) % loop.length]]));
  }
  return d;
}

const inRoom = (room) => (x, y) => room.rects.some(([rx, ry, w, h]) => x >= rx && x < rx + w && y >= ry && y < ry + h);
const inside = (x, y) => x >= 0 && y >= 0 && x < SIZE && y < SIZE;
const rooms = map.rooms.map((room) => {
  return { kind: room.kind, path: outline(inRoom(room)) };
});
const anyRoom = (x, y) => map.rooms.some((room) => inRoom(room)(x, y));
const mass = outline((x, y) => inside(x, y) && !anyRoom(x, y), true);

// Every route segment must stay on floor (edges count).
const onFloor = (x, y) => map.rooms.some((r) => r.rects.some(([a, b, w, h]) => x >= a && x <= a + w && y >= b && y <= b + h));
const lengths = [0];
route.points.forEach((p, i) => {
  if (!i) return;
  const q = route.points[i - 1];
  for (let t = 0; t <= 1; t += 0.01) if (!onFloor(q[0] + (p[0] - q[0]) * t, q[1] + (p[1] - q[1]) * t)) throw new Error(`route segment ${i} leaves the floor`);
  lengths.push(lengths[i - 1] + Math.hypot(p[0] - q[0], p[1] - q[1]));
});
const stops = route.stops.map(({ room, ...stop }) => {
  const [x, y] = route.points[stop.point];
  const r = map.rooms.find((r) => r.name === room);
  if (!r || !r.rects.some(([a, b, w, h]) => x > a && x < a + w && y > b && y < b + h)) throw new Error(`stop ${stop.id} is not inside its room`);
  return { ...stop, at: route.points[stop.point], d: lengths[stop.point] };
});

// The timeline: one straight north to south run, one evenly spaced point per entry, in date order.
const [first, last] = route.corridor;
const dated = stops.filter((s) => s.when);
const run = route.points.slice(first, last + 1);
if (dated.length !== run.length || dated.some((s, k) => s.point !== first + k)) throw new Error('timeline entries must be the corridor points');
run.forEach(([x, y], k) => {
  if (!k) return;
  if (x !== run[0][0] || y <= run[k - 1][1] || y - run[k - 1][1] !== run[1][1] - run[0][1]) throw new Error('corridor must run straight south, evenly spaced');
  if (dated[k].when < dated[k - 1].when) throw new Error('timeline entries out of date order');
});
// Each Jan 1 sits between the two entries either side of it, in proportion to their dates.
const years = route.years.map((year) => {
  const k = dated.findIndex((s, i) => i && s.when > year);
  const a = dated[k - 1], b = dated[k];
  const t = (year - a.when) / (b.when - a.when);
  return { year, at: [a.at[0], +(a.at[1] + (b.at[1] - a.at[1]) * t).toFixed(2)] };
});

writeFileSync('src/map-data.js',
  '// Generated by scripts/build-map.mjs. Do not edit.\n' +
  `window.SITE_MAP = ${JSON.stringify({ mass, walls, rooms, points: route.points, stops, years, labels: route.labels, callouts: route.callouts })};\n`);

// Static thumbnails for the plain page: whole map, route walked so far, this stop marked.
// The buy one shows the four callouts instead.
rmSync('assets/map', { recursive: true, force: true });
mkdirSync('assets/map', { recursive: true });
const floor = { site: '#989874', spawn: '#8C8C8C', room: '#7A7A7A' };
const plan = (inner) => '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">' +
  '<rect width="100" height="100" fill="#ECE8E1"/>' +
  rooms.map((r) => `<path d="${r.path}" fill="${floor[r.kind]}"/>`).join('') + inner + '</svg>\n';
const dot = ([x, y], r = 1.8) => `<circle cx="${x}" cy="${y}" r="${r}" fill="#FF4655" stroke="#ECE8E1" stroke-width="0.6"/>`;
for (const stop of stops.filter((s) => ['position', 'why-riot', 't-yanglab', 'projects', 'close'].includes(s.id))) {
  const walked = route.points.slice(0, stop.point + 1).map((p) => p.join(',')).join(' ');
  writeFileSync(`assets/map/${stop.id}.svg`, plan(`<polyline points="${walked}" fill="none" stroke="#FF4655" stroke-width="0.9"/>${dot(stop.at)}`));
}
writeFileSync('assets/map/buy.svg', plan(dot(route.points[0], 1.4) + route.callouts.map((c) =>
  `<text x="${c.at[0]}" y="${c.at[1]}" text-anchor="middle" dominant-baseline="middle" font-family="Barlow, Arial, sans-serif" font-weight="600" font-size="3.2" fill="#0F1923" stroke="#ECE8E1" stroke-width="0.8" paint-order="stroke">${c.text}</text>`).join('')));
console.log(`${rooms.length} rooms, route ${lengths.at(-1).toFixed(1)} units, ${stops.length} stops, corridor ${run[0]} to ${run.at(-1)}`);
